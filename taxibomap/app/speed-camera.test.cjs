const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(`${__dirname}/speed-camera.js`,'utf8')+'\nglobalThis.Camera = SpeedAwareCamera;',context);
const Camera = context.Camera;
const camera = new Camera({pitch:70,zoom:19.3,anchor:.62},0);
assert.equal(camera.target().pitch,70,'unknown speed holds the initial view');
camera.update(0,10,Infinity,0);
let view = camera.frame(16);
assert.ok(view.pitch>10 && view.pitch<70,'first fix transitions gradually');
for(let now=32;now<=4000;now+=16) camera.frame(now);
assert.ok(camera.view.pitch<11,'stopped view becomes nearly top-down');
camera.update(25,10,Infinity,5000);
const highway = camera.target();
assert.ok(highway.pitch>60 && highway.zoom<18.3,'highway looks ahead');
const pitchBefore = camera.view.pitch;
view=camera.frame(5016);
assert.ok(view.pitch>pitchBefore && view.pitch<highway.pitch,'speed changes do not jump');
const lastSpeed=camera.speed;
camera.update(null,10,Infinity,6000);
assert.equal(camera.speed,lastSpeed,'missing speed does not imply stopped');
camera.update(0,100,Infinity,7000);
assert.equal(camera.speed,lastSpeed,'poor accuracy is ignored');
camera.update(25,10,30,8000);
assert.ok(camera.target().pitch<=45 && camera.target().zoom>=19,'junction stays visible');
const steady = new Camera({pitch:45,zoom:18.7,anchor:.6},0);
steady.update(40/3.6,10,Infinity,0);
steady.update(41/3.6,10,Infinity,1000);
assert.ok(Math.abs(steady.speed-40)<.01,'small speed jitter is ignored');
console.log('PASS speed views, smooth transitions, unknown speed, accuracy, junctions and jitter');
